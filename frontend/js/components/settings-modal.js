// Settings modal - schema-driven config editor across 7 sections.
// Fetches the full AppConfig via GET /api/settings, renders a schema-driven
// form (6 flat structs + the dynamic clients array), and PUTs the edited
// config back. The PUT writes config.toml and triggers a hot-reload - the
// reloader re-applies structural changes (pool, peer server, NAT, log
// filter, HTTP bind) and broadcasts config_reloaded. Running audits are
// unaffected (frozen on their startup config).

