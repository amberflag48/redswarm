function settingsFieldId(section, key) { return 'set-' + section + '-' + key; }

export function renderSettingsClients() {
  const container = document.getElementById('settings-clients');
  if (!container || !state.settingsConfig) return;
  container.innerHTML = state.settingsConfig.clients.map(function (c, i) { return clientCardHtml(i, c); }).join('');
}

export function populateSettingsFields() {
  for (const [section] of SETTINGS_SECTIONS) {
    if (section === 'clients') continue;
    for (const f of SETTINGS_SCHEMA[section]) {
      const id = settingsFieldId(section, f.key);
      const cfgSection = f.cfg || section;
      const v = state.settingsConfig[cfgSection][f.key];
      if (f.type === 'bool') {
        const el = document.getElementById(id);
        if (el) el.checked = !!v;
      } else if (f.type === 'speed') {
        setSpeedField(id + '-val', id + '-unit', v ?? 0);
      } else if (f.type === 'amount') {
        setByteField(id + '-val', id + '-unit', v ?? 0);
      } else {
        const el = document.getElementById(id);
        if (el) el.value = v;
      }
    }
  }
}

export function switchSettingsSection(section) {
  state.settingsActiveSection = section;
  document.querySelectorAll('#settings-nav button').forEach(function (b) {
    b.classList.toggle('active', b.dataset.section === section);
  });
  document.querySelectorAll('.settings-pane').forEach(function (p) {
    p.classList.toggle('active', p.dataset.section === section);
  });
}

function collectSettingsClients() {
  const clients = [];
  document.querySelectorAll('.client-card').forEach(function (card) {
    if (card.dataset.idx === 'cap') return; // skip capture-modal card
    const c = collectOneClient(card.dataset.idx);
    if (c) clients.push(c);
  });
  return clients;
}

function collectSettings() {
  const cfg = state.settingsConfig;
  for (const [section] of SETTINGS_SECTIONS) {
    if (section === 'clients') continue;
    for (const f of SETTINGS_SCHEMA[section]) {
      const id = settingsFieldId(section, f.key);
      const cfgSection = f.cfg || section;
      if (f.type === 'bool') {
        const el = document.getElementById(id);
        if (el) cfg[cfgSection][f.key] = el.checked;
      } else if (f.type === 'speed' || f.type === 'amount') {
        cfg[cfgSection][f.key] = getSpeedBps(id + '-val', id + '-unit');
      } else if (f.type === 'number') {
        const el = document.getElementById(id);
        if (el) cfg[cfgSection][f.key] = el.value === '' ? 0 : Number(el.value);
      } else {
        const el = document.getElementById(id);
        if (el) cfg[cfgSection][f.key] = el.value;
      }
    }
  }
  cfg.clients = collectSettingsClients();
  return cfg;
}

export function addSettingsClient() {
  if (!state.settingsModalOpen) return;
  state.settingsConfig.clients = collectSettingsClients();
  state.settingsConfig.clients.unshift(defaultClient());
  renderSettingsClients();
  // Expand the newly added card (index 0) and switch to Clients section
  switchSettingsSection('clients');
  const card = document.querySelector('.client-card[data-idx="0"]');
  if (card) {
    expandClientCard(card);
    const firstInput = card.querySelector('input, textarea, select');
    if (firstInput) firstInput.focus();
  }
  updateSaveButton();
}

export async function removeSettingsClient(idx) {
  if (!state.settingsModalOpen) return;
  // Collect current form state to get the client name for the prompt
  const clients = collectSettingsClients();
  const client = clients[idx];
  if (!client) return;
  const name = client.label ? clientDisplayName(client) : 'New client';
  const confirmed = await showConfirm(
    'Remove client',
    'Remove <strong>' + escHtml(name) + '</strong>? This cannot be undone.',
    [CONFIRM_CANCEL, { label: 'Remove', class: 'btn-danger', value: 'ok' }]
  );
  if (confirmed !== 'ok') return;
  state.settingsConfig.clients = collectSettingsClients();
  state.settingsConfig.clients.splice(idx, 1);
  renderSettingsClients();
  updateSaveButton();
}

export function openSettingsModal() {
  const sm = document.getElementById('settings-modal');
  openModalEl(sm, closeSettingsModal);
  state.settingsModalOpen = true;
  populateSettingsFields();
  renderSettingsClients();
  updateSettingsGoalVisibility();
  switchSettingsSection('server');
  const sc = document.getElementById('settings-content');
  state.settingsFormSnapshot = snapshotForm(sc);
  updateSaveButton();
  focusFirst(sm);
}

// Shared visibility driver - delegates to goal-form.js with the settings
// field IDs. Uses hideAllWhenDisabled (settings modal hides each sub-field's
// parent .field div when the goal is unchecked). Re-exported so init.js
// can call it from the change listener.
export function updateSettingsGoalVisibility() {
    updateGoalFieldVisibility(SETTINGS_GOAL_IDS, { hideAllWhenDisabled: true, timeAsPicker: false });
}

export function settingsIsDirty() {
  return isFormDirty(document.getElementById('settings-content'), state.settingsFormSnapshot);
}

export function updateSaveButton() {
  const btn = document.getElementById('save-settings-btn');
  if (!btn) return;
  btn.disabled = !settingsIsDirty();
}

// Reset settings modal state after the overlay is closed. Keeps
// state.settingsConfig cached - SSE config_reloaded keeps it fresh, so
// reopening is instant (no re-fetch). Only clears modal-specific state.
function resetSettingsModal() {
  state.settingsModalOpen = false;
  state.settingsFormSnapshot = '';
  state.settingsActiveSection = 'server';
  clearSettingsErrors();
  document.getElementById('settings-clients').innerHTML = '';
  const btn = document.getElementById('save-settings-btn');
  if (btn) { btnReset(btn); btn.textContent = 'Save'; }
  clearPending('save-settings');
}

export const closeSettingsModal = registerModal({ isDirty: settingsIsDirty, noun: 'changes', reset: resetSettingsModal });

export function saveSettings(btn) {
  if (!state.settingsModalOpen) return;
  btnLoading(btn);
  const cfg = collectSettings();
  state.settingsSaveAt = Date.now();
  const signal = pendingSignal('save-settings');
  request('/api/settings', {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(cfg),
    signal,
  }).then(function (r) {
    if (!r.ok) {
      showSettingsErrors(r.text);
      toast('Validation failed - see highlighted fields', 'error');
      btnReset(btn);
      state.settingsSaveAt = 0;
      updateSaveButton();
      return;
    }
    clearSettingsErrors();
    state.settingsFormSnapshot = '';
    toast('Settings saved', 'success');
    closeSettingsModal();
  });
}

// Parse a backend validation error string and highlight the offending fields.
// Backend errors look like "clients[].label must not be empty (client `...`)"
// or "peer_server.max_connections must be >= 1".
function showSettingsErrors(errMsg) {
  clearSettingsErrors();
  // Try to match "clients[].<field>" with optional client name in backticks
  const clientMatch = errMsg.match(/clients\[\]\.(\w+).*client `([^`]+)`/);
  if (clientMatch) {
    const field = clientMatch[1];
    const clientName = clientMatch[2];
    // Find the client card matching the name
    const cards = document.querySelectorAll('.client-card');
    for (let i = 0; i < cards.length; i++) {
      const p = clientFieldId(i, '');
      const labelEl = document.getElementById(p + 'label');
      const versionEl = document.getElementById(p + 'version');
      if (labelEl && versionEl) {
        const name = clientDisplayName({ label: labelEl.value, version: versionEl.value, peer_id_prefix: document.getElementById(p + 'peer_id_prefix').value });
        if (name === clientName) {
          const fieldEl = document.getElementById(p + field);
          if (fieldEl) {
            addFieldError(fieldEl.closest('.field'), errMsg);
          }
          expandClientCard(cards[i]);
          return;
        }
      }
    }
  }
  // Generic section.field error - try to highlight in settings panes
  const sectionMatch = errMsg.match(/^(\w+)\.(\w+)/);
  if (sectionMatch) {
    const section = sectionMatch[1];
    const key = sectionMatch[2];
    const el = document.getElementById(settingsFieldId(section, key)) || document.getElementById(settingsFieldId('server', key));
    if (el) {
      addFieldError(el.closest('.field'), errMsg);
    }
    return;
  }
  // Fallback: just show the toast
  toast(errMsg, 'error');
}

function clearSettingsErrors() {
  clearFieldErrors(document);
}
